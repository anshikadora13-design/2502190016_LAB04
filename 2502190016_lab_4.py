"""## Basic SciPy Program"""

import numpy as np
from scipy import stats

# Generate some sample data using NumPy
sample_data = np.array([12, 15, 13, 18, 20, 14, 16, 17, 19, 11, 22, 25])

print("Sample Data:", sample_data)

"""### Descriptive Statistics with SciPy"""

# Calculate various descriptive statistics using scipy.stats
mean = np.mean(sample_data)
median = np.median(sample_data)
std_dev = np.std(sample_data, ddof=1) # ddof=1 for sample standard deviation
variance = np.var(sample_data, ddof=1) # ddof=1 for sample variance
skewness = stats.skew(sample_data)
kurtosis = stats.kurtosis(sample_data)

print(f"Mean: {mean:.2f}")
print(f"Median: {median:.2f}")
print(f"Standard Deviation: {std_dev:.2f}")
print(f"Variance: {variance:.2f}")
print(f"Skewness: {skewness:.2f}")
print(f"Kurtosis: {kurtosis:.2f}")

"""### Hypothesis Testing with SciPy (e.g., T-test)"""

# Let's perform a one-sample t-test
# We'll test if the mean of our sample data is significantly different from a population mean of 15.
population_mean = 15
t_statistic, p_value = stats.ttest_1samp(sample_data, population_mean)

print(f"T-statistic: {t_statistic:.3f}")
print(f"P-value: {p_value:.3f}")

# Interpret the result
alpha = 0.05 # Significance level
if p_value < alpha:
    print(f"Since p-value ({p_value:.3f}) < alpha ({alpha}), we reject the null hypothesis.")
    print(f"The sample mean is significantly different from {population_mean}.")
else:
    print(f"Since p-value ({p_value:.3f}) >= alpha ({alpha}), we fail to reject the null hypothesis.")
    print(f"The sample mean is not significantly different from {population_mean}.")

