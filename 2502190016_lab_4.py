"""## Daily Hours Worked Calculation"""

import pandas as pd
import numpy as np
from datetime import time, timedelta

# Generate sample data for workers and their daily clock-in/out times
np.random.seed(42)
num_workers = 5
num_days = 3

workers = [f'Worker_{i+1}' for i in range(num_workers)]
dates = pd.to_datetime([f'2023-10-{d+1}' for d in range(num_days)])

data = []
for worker in workers:
    for date in dates:
        # Simulate clock-in and clock-out times
        # Clock-in between 8:00 and 9:00 AM
        clock_in_hour = np.random.randint(8, 9)
        clock_in_minute = np.random.randint(0, 60)
        clock_in_time = time(clock_in_hour, clock_in_minute)

        # Clock-out between 4:00 PM and 6:00 PM
        clock_out_hour = np.random.randint(16, 18)
        clock_out_minute = np.random.randint(0, 60)
        clock_out_time = time(clock_out_hour, clock_out_minute)

        data.append({
            'Worker': worker,
            'Date': date.date(), # Store only the date part
            'Clock In': clock_in_time,
            'Clock Out': clock_out_time
        })

df_work_times = pd.DataFrame(data)

print("Sample Worker Clock-In/Out Data:")
display(df_work_times.head())

"""Now, let's calculate the total hours worked for each worker on each day."""

# Convert 'Clock In' and 'Clock Out' to datetime objects for calculation
# Combine date with time
df_work_times['Clock In Datetime'] = df_work_times.apply(lambda row: pd.to_datetime(str(row['Date']) + ' ' + str(row['Clock In'])), axis=1)
df_work_times['Clock Out Datetime'] = df_work_times.apply(lambda row: pd.to_datetime(str(row['Date']) + ' ' + str(row['Clock Out'])), axis=1)

# Calculate duration worked
df_work_times['Duration'] = df_work_times['Clock Out Datetime'] - df_work_times['Clock In Datetime']

# Convert duration to hours (float)
df_work_times['Hours Worked'] = df_work_times['Duration'].dt.total_seconds() / 3600

# Display the results
print("Worker Daily Hours Worked:")
display(df_work_times[['Worker', 'Date', 'Clock In', 'Clock Out', 'Hours Worked']].head())

"""We can also aggregate to see total hours worked per worker across all days or mean daily hours."""

# Aggregate total hours worked per worker
total_hours_per_worker = df_work_times.groupby('Worker')['Hours Worked'].sum().reset_index()
print("Total Hours Worked Per Worker (Across all days):")
display(total_hours_per_worker)

# Aggregate mean daily hours worked per worker
mean_daily_hours_per_worker = df_work_times.groupby('Worker')['Hours Worked'].mean().reset_index()
print("Mean Daily Hours Worked Per Worker:")
display(mean_daily_hours_per_worker)

